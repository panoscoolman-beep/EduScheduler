"""Κατάλογος τάξεων και κατευθύνσεων/τομέων — ΜΙΑ πηγή αλήθειας.

Το frontend δεν κρατά δικό του αντίγραφο: το κατεβάζει από το
`GET /api/students/grade-options`. Έτσι μια αλλαγή εδώ (π.χ. νέος τομέας
ΕΠΑΛ) φαίνεται αμέσως παντού — φόρμα, εξαγωγή, έλεγχοι.

Δομή: `GRADES` = οι τάξεις με τη σειρά που τις σκέφτεται ο χρήστης·
`TRACKS` = ποιες κατευθύνσεις/τομείς έχει κάθε τάξη (όσες λείπουν = καμία).
Τα κείμενα αποθηκεύονται ΟΠΩΣ ΕΙΝΑΙ στη βάση (ελεύθερο VARCHAR), οπότε
παλιές τιμές δεν σπάνε αν αλλάξει ο κατάλογος.
"""
from __future__ import annotations

GRADES: list[str] = [
    "Ε΄ Δημοτικού",
    "ΣΤ΄ Δημοτικού",
    "Α΄ Γυμνασίου",
    "Β΄ Γυμνασίου",
    "Γ΄ Γυμνασίου",
    "Α΄ Λυκείου",
    "Α΄ ΕΠΑΛ",
    "Β΄ Λυκείου",
    "Β΄ ΕΠΑΛ",
    "Γ΄ Λυκείου",
    "Γ΄ ΕΠΑΛ",
]

# Γενικό Λύκειο: ομάδες προσανατολισμού.
_GEL_B = [
    "Θετικών Σπουδών (Θετική)",
    "Ανθρωπιστικών Σπουδών (Θεωρητική)",
]
_GEL_C = [
    "Ανθρωπιστικών Σπουδών (1ο πεδίο)",
    "Θετικών Σπουδών (2ο πεδίο)",
    "Σπουδών Υγείας (3ο πεδίο)",
    "Σπουδών Οικονομίας & Πληροφορικής (4ο πεδίο)",
]

# ΕΠΑΛ: τομείς (Β΄ τάξη επιλέγει τομέα, Γ΄ συνεχίζει στον ίδιο τομέα με
# ειδικότητα — κρατάμε τον τομέα, η ειδικότητα γράφεται στο ίδιο πεδίο αν
# χρειαστεί, γι' αυτό το πεδίο δέχεται και ελεύθερο κείμενο).
_EPAL_SECTORS = [
    "Γεωπονίας, Τροφίμων και Περιβάλλοντος",
    "Διοίκησης και Οικονομίας",
    "Δομικών Έργων, Δομημένου Περιβάλλοντος και Αρχιτεκτονικού Σχεδιασμού",
    "Εφαρμοσμένων Τεχνών",
    "Ηλεκτρολογίας, Ηλεκτρονικής και Αυτοματισμού",
    "Μηχανολογίας",
    "Ναυτιλιακών Επαγγελμάτων",
    "Πληροφορικής",
    "Υγείας - Πρόνοιας - Ευεξίας",
]

TRACKS: dict[str, list[str]] = {
    "Β΄ Λυκείου": _GEL_B,
    "Γ΄ Λυκείου": _GEL_C,
    "Β΄ ΕΠΑΛ": _EPAL_SECTORS,
    "Γ΄ ΕΠΑΛ": _EPAL_SECTORS,
}

# Πώς λέγεται το δεύτερο πεδίο ανά τάξη (ΓΕΛ: κατεύθυνση, ΕΠΑΛ: τομέας).
TRACK_LABELS: dict[str, str] = {
    "Β΄ Λυκείου": "Κατεύθυνση",
    "Γ΄ Λυκείου": "Κατεύθυνση",
    "Β΄ ΕΠΑΛ": "Τομέας",
    "Γ΄ ΕΠΑΛ": "Τομέας",
}

DEFAULT_TRACK_LABEL = "Κατεύθυνση / Τομέας"


def tracks_for(grade: str | None) -> list[str]:
    """Οι διαθέσιμες κατευθύνσεις/τομείς μιας τάξης (κενή λίστα = καμία)."""
    return TRACKS.get((grade or "").strip(), [])


def has_tracks(grade: str | None) -> bool:
    return bool(tracks_for(grade))


def track_label(grade: str | None) -> str:
    return TRACK_LABELS.get((grade or "").strip(), DEFAULT_TRACK_LABEL)


def clean_track(grade: str | None, track: str | None) -> str | None:
    """Η κατεύθυνση κρατιέται ΜΟΝΟ όταν η τάξη έχει νόημα να έχει.

    Αλλιώς μηδενίζεται — αλλιώς ένας μαθητής που μετακινήθηκε από Β΄ Λυκείου
    σε Α΄ Λυκείου θα κουβαλούσε «Θετική» για πάντα."""
    value = (track or "").strip()
    if not value or not has_tracks(grade):
        return None
    return value


def catalog() -> dict:
    """Ό,τι χρειάζεται το frontend για να χτίσει τα δύο dropdown."""
    return {
        "grades": GRADES,
        "tracks": TRACKS,
        "track_labels": TRACK_LABELS,
        "default_track_label": DEFAULT_TRACK_LABEL,
    }
